"""Generate matching Android resources and a known-status lookup. No runtime source rewriting."""
import hashlib
import json
from pathlib import Path
from xml.sax.saxutils import escape
ROOT = Path(__file__).resolve().parents[1]


def key(text):
    return 'ui_'+hashlib.sha1(text.encode()).hexdigest()[:12]


def main():
    translations = json.loads((ROOT/'app/viewer/i18n/translations.json').read_text(encoding='utf8'))
    for locale in ('values', 'values-zh'):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>',
                 '    <string name="app_name">'+('虹膜空间' if locale.endswith('-zh') else 'IrisBox · Android Container')+'</string>']
        for original, english in sorted(translations.items()):
            value = original.replace('RootVMOS', '虹膜空间').replace('返回 Iris', '返回虹膜空间').replace('Iris_实例', 'IrisBox_实例') if locale.endswith('-zh') else english
            value = escape(value).replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
            # Android trims unquoted spaces, which are intentional in fragments.
            lines.append('    <string name="'+key(original)+'" formatted="false">"'+value+'"</string>')
        lines.append('</resources>')
        out = ROOT/'app/viewer/res'/locale/'strings.xml'
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text('\n'.join(lines)+'\n', encoding='utf8', newline='\n')
    lines = ['package com.rootvmos.viewer;', '// Generated by tools/generate_i18n.py.', 'final class LegacyText {',
             '    static final java.util.Map<String,Integer> IDS = new java.util.HashMap<>();', '    static {']
    for original in sorted(translations):
        lines.append('        IDS.put('+json.dumps(original, ensure_ascii=False)+', R.string.'+key(original)+');')
    lines += ['    }', '}']
    (ROOT/'app/viewer/src/com/iris/viewer/buffer/LegacyText.java').write_text('\n'.join(lines)+'\n', encoding='utf8', newline='\n')
    print('Generated EN/ZH resources:', len(translations), 'matching entries')


if __name__ == '__main__':
    main()
